#!/usr/bin/env python3
"""
Write the map of the code (P678): which CLI runs which Operation, what each module of an area does and which test file
holds its tests, and the keys of each registry. A person or Claude looking for code starts there.

    python3 tools/map.py            # prints docs/guide/map.md
    python3 tools/map.py --write    # writes it; tests/test_map.py fails while the page is stale
"""

import argparse
import ast
import functools
import importlib
import operator
import sys
from collections import namedtuple
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = "docs/guide/map.md"
HEADER = "Generated by `python3 tools/map.py --write` from the code. Do not edit it: change the code, then run that command."
NO_DOCSTRING = "(no docstring)"
SENTENCE = 100  # characters a module's line may hold
SHOWN_TESTS = 3  # test files a module shows before "N more"
#: Value: a registry the page lists: its label, the module and attribute that hold it, and the function that gives
#: one key from one of its entries (`str` for a dict, whose entries are the keys).
Registry = namedtuple("Registry", "label module attribute key")
REGISTRIES = (
    Registry("spark.bench.OPERATIONS", "spark.bench", "OPERATIONS", str),
    Registry("spark.idea.OPERATIONS", "spark.idea", "OPERATIONS", str),
    Registry("parts.OPERATIONS", "parts", "OPERATIONS", operator.itemgetter(0)),
    Registry("breadboard.WIRING_VIEWS", "breadboard", "WIRING_VIEWS", operator.itemgetter(0)),
    Registry("breadboard.DRAWING_RENDERERS", "breadboard", "DRAWING_RENDERERS", operator.attrgetter("FILE_NAME")),
)


# --- MVP ---
def tests_cell(tests):
    """The table cell of a module's test files: the first three, then how many more, or "none"."""
    shown = ["`%s`" % test for test in tests[:SHOWN_TESTS]] + (["%d more" % (len(tests) - SHOWN_TESTS)] if len(tests) > SHOWN_TESTS else [])
    return ", ".join(shown) or "none"


def first_line(node):
    """
    The first sentence of a module's docstring: its first paragraph on one line, cut at the first ". ", or at a word
    within SENTENCE characters with "…" when longer. NO_DOCSTRING when it has none.
    """
    paragraph = " ".join((ast.get_docstring(node, clean=True) or "").strip().split("\n\n")[0].split())
    head, dot, _ = paragraph.partition(". ")
    sentence = head + ("." if dot else "")
    if len(sentence) > SENTENCE:
        sentence = sentence[:SENTENCE - 1].rsplit(" ", 1)[0] + "…"
    return sentence or NO_DOCSTRING


def parse(path):
    return ast.parse(path.read_text())


def operation_names(tree):
    """{class name: the Operation's printed name} for each class in `tree` that has `Operation` among its bases and sets a string `name`."""
    found = {}
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and "Operation" in [getattr(base, "id", getattr(base, "attr", "")) for base in node.bases]:
            for statement in node.body:
                if (isinstance(statement, ast.Assign) and [t.id for t in statement.targets if isinstance(t, ast.Name)] == ["name"]
                        and isinstance(statement.value, ast.Constant) and isinstance(statement.value.value, str)):
                    found[node.name] = statement.value.value
    return found


@functools.lru_cache(maxsize=None)
def imports_of(test):
    """{module: names} for each `from module import names` and `import module [as x]` in the file `test` (names are empty for `import`)."""
    found = {}
    for node in ast.walk(parse(test)):
        if isinstance(node, ast.ImportFrom) and node.module:
            found.setdefault(node.module, set()).update(alias.name for alias in node.names)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                found.setdefault(alias.name, set())
    return found


def tests_of(root, package, stem):
    """
    The test files in `tests/` that import the module `stem` of `package`, as `from package.stem import ...`,
    `from package import stem` or `import package.stem [as x]`. `test_<stem>.py` comes first when it is one.
    """
    found = ["tests/" + test.name for test in sorted((root / "tests").glob("test_*.py"))
             if "%s.%s" % (package, stem) in imports_of(test) or stem in imports_of(test).get(package, ())]
    return sorted(found, key=lambda test: test != "tests/test_%s.py" % stem)


class AreaMap:
    """
    Value: the map of the code, read from the files. `clis` is [(script, [(operation, class path)])], `areas` is
    [(area, its first docstring line, [(module file, its first docstring line, the test files that import it)])], and
    `registries` is [(label, [key])]. `AreaMap.of(root)` reads them and `markdown()` is the page.
    """

    def __init__(self, clis, areas, registries):
        self.clis, self.areas, self.registries = clis, areas, registries

    @classmethod
    def of(cls, root, registries=REGISTRIES):
        root = Path(root)
        spark = root / "scripts" / "spark"
        areas = []
        for folder in sorted(path for path in spark.iterdir() if (path / "__init__.py").is_file()):
            modules = [(path.name, first_line(parse(path)), tests_of(root, "spark.%s" % folder.name, path.stem))
                       for path in sorted(folder.glob("*.py")) if path.name != "__init__.py"]
            areas.append((folder.name, first_line(parse(folder / "__init__.py")), modules))
        return cls(cls.clis_of(root), areas, cls.registries_of(root, registries))

    @staticmethod
    def clis_of(root):
        """
        Each script in `scripts/` with the Operations it imports from an area, as `from spark.<area>.<module> import
        <Class>` only (`import spark.<area>.<module>` is not read). A module that is not there is skipped.
        """
        clis = []
        for script in sorted((root / "scripts").glob("*.py")):
            found = []
            for node in ast.walk(parse(script)):
                if isinstance(node, ast.ImportFrom) and (node.module or "").startswith("spark.") and node.module.count(".") == 2:
                    module = root / "scripts" / Path(*node.module.split(".")).with_suffix(".py")
                    names = operation_names(parse(module)) if module.is_file() else {}
                    found += [(names[alias.name], "%s.%s" % (node.module, alias.name)) for alias in node.names if alias.name in names]
            if found:
                clis.append((script.name, sorted(found)))
        return clis

    # --- Later, not MVP: reads the keys by importing the registry module; ast would avoid the import ---
    @staticmethod
    def registries_of(root, registries):
        """Each registry's keys in the order the code lists them. This imports the module that holds it."""
        if str(root / "scripts") not in sys.path:
            sys.path.insert(0, str(root / "scripts"))
        return [(one.label, [one.key(entry) for entry in getattr(importlib.import_module(one.module), one.attribute)])
                for one in registries]
    # --- end ---

    def markdown(self):
        lines = ["# Map of the code", "", HEADER, "", "## Commands", "", "| CLI in `scripts/` | Operations |", "|---|---|"]
        lines += ["| `%s` | %s |" % (script, ", ".join("`%s` (`%s`)" % found for found in found_ops)) for script, found_ops in self.clis]
        for area, about, modules in self.areas:
            lines += ["", "## spark/%s: %s" % (area, about), "", "| Module | What it does | Tests that import it |", "|---|---|---|"]
            lines += ["| `%s` | %s | %s |" % (file, about.replace("|", "\\|"), tests_cell(tests))
                      for file, about, tests in modules]
        lines += ["", "## Registries", ""]
        lines += ["- `%s`: %s" % (label, ", ".join(keys)) for label, keys in self.registries]
        return "\n".join(lines) + "\n"
# --- end MVP ---


def main():
    parser = argparse.ArgumentParser(description="Print the map of the code, or write it to %s." % PAGE)
    parser.add_argument("--write", action="store_true", help="write %s instead of printing" % PAGE)
    if parser.parse_args().write:
        (ROOT / PAGE).write_text(AreaMap.of(ROOT).markdown())
        print("wrote %s" % PAGE)
    else:
        print(AreaMap.of(ROOT).markdown(), end="")


if __name__ == "__main__":
    main()
