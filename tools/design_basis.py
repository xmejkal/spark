#!/usr/bin/env python3
"""
Write the design basis (P1102): what every interface of spark shows, read from the code. The phases with their usual actor
and plain name, the statuses with their mark, the actors, the offers, the Operations and the steps that are not built yet
(`flow_codes.UNBUILT_STEPS`, P1119), each with a fixed key. The person's moment at each phase is hand-written here, with a
date.

    python3 tools/design_basis.py            # prints docs/guide/design-basis.md
    python3 tools/design_basis.py --write    # writes it and docs/guide/design-basis.json; tests/test_design_basis.py fails while they are stale
"""

import argparse
import importlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKDOWN_PAGE = "docs/guide/design-basis.md"
JSON_PAGE = "docs/guide/design-basis.json"
HEADER = "Generated by `python3 tools/design_basis.py --write` from the code. Do not edit it: change the code, then run that command."
HAND_WRITTEN = "2026-11-24"
#: The person's moment at each phase, hand-written (P1102, proposed text for the PO's review).
MOMENTS = {
    "idea": "At the desk, in a chat with Claude: you say what you want the gadget to do.",
    "needs": "At the desk: you read the needs Claude wrote from your goal and agree or change them.",
    "parts": "At the desk: you pick a part for each need, the parts you own first.",
    "requirements": "At the desk: Claude writes the parts list from your picks. You wait.",
    "build": "At the desk: spark builds the board files in seconds. You read what built and what was skipped.",
    "breadboard": "At the bench, hands busy, the USB cable out: you wire one step at a time, often from a phone.",
    "firmware": "At the desk, in the chat: you say what the gadget does, and Claude writes the firmware.",
    "simulate": "At the desk: you run the simulation in your terminal and read whether it passed.",
    "deploy": "At the bench, the board on USB: you run the deploy in your terminal and look at the board.",
}
NO_WORD = "(the mark alone)"
#: The Op cell of a chat offer, which has no step of spark's: Claude does its job in the chat (P1122).
NO_OP = "none"
INTRO = """How to read this page:

- The moment of each phase and of each unbuilt step is hand-written, last on %s. The unbuilt steps stand in
  `flow_codes.UNBUILT_STEPS`, which the page's station line reads too.
- The phases with their plain names, the statuses, actors and Operations are read from the code.
- The offer kinds, their phases, labels and tells are read from `flow_codes.OFFER_KINDS`. Only each step is written in the tool.
- A key is `<group>:<name>`, and the group makes it unique.
- A phase reader is the code that reads one phase of a project. The usual actor of a phase is the one its reader names.
  In some states the guide names another actor, and `guide.now.by` holds the actual one.
- This page does not list which statuses each phase can show. Each phase reader decides that from the project's files.
- An offer key names a kind of offer, not one project's offer. Its label keeps its `%%s` places.
- "From the page" says whether a click on the project page can send the offer. If it says no, you ask Claude in the chat.
- A tell is one sentence for Claude that names a job only Claude does. An offer with a tell is a chat offer, with no op.
- A status with no word is shown by its mark alone.
- The summary of an Operation is the one that `--describe` prints.""" % HAND_WRITTEN


def spark_modules():
    """The spark modules this page reads, imported when it runs, so a test that swaps a list in a module is seen."""
    if str(ROOT / "scripts") not in sys.path:
        sys.path.insert(0, str(ROOT / "scripts"))
    names = ("flow.flow_codes", "flow.phase_readers", "flow.run_request", "flow.offer_steps", "operation_catalogue",
             "core.describe_operations")
    return [importlib.import_module("spark." + name) for name in names]


def slug(name):
    return "none" if name is None else str(name).replace(" ", "-")


def steps_by_kind(flow_codes, offer_steps):
    """{offer kind: a function that gives its NextStep with placeholder values}, for each kind with a step. The step's op
    is the only thing read from it. The kinds, their phases, labels and tells are `flow_codes.OFFER_KINDS` (P1115)."""
    return {flow_codes.PICK: lambda: offer_steps.pick_step("/project", "need", "id", "name"),
            flow_codes.WRITE_REQUIREMENTS: lambda: offer_steps.requirements_step("/project"),
            flow_codes.BUILD_BOARD: lambda: offer_steps.build_step("/project"),
            flow_codes.NEEDS_DROP: lambda: offer_steps.drop_step("/project", "need")}


# Puts scripts/ on sys.path, so that the import below finds spark.
spark_modules()
from spark.flow import flow_codes as _codes, offer_steps as _steps  # noqa: E402

#: The step of each offer kind that has one. A kind with none is a job Claude does in the chat, so its op is None.
STEPS = steps_by_kind(_codes, _steps)


class DesignBasis:
    """
    Value: the design basis, `items` as a list of dicts, each with a `key`. `DesignBasis.of()` reads the code,
    `json_text()` and `markdown()` are the two files, and `missing()` names a phase with no moment or a moment with no phase.
    """

    def __init__(self, items):
        self.items = items

    @classmethod
    def of(cls):
        flow_codes, phase_readers, run_request, _, catalogue, describe = spark_modules()
        usual = {reader.PHASE: reader.BY for reader in phase_readers.READERS}
        items = [{"key": "phase:" + phase, "phase": phase, "name": flow_codes.PHASE_NAMES.get(phase), "usual_by": usual[phase],
                  "moment": MOMENTS.get(phase, "")} for phase in flow_codes.PHASES]
        items += [{"key": "status:" + slug(status), "status": status, "word": word, "mark": mark}
                  for status, (word, mark) in phase_readers.MARKS.items()]
        items += [{"key": "by:" + slug(name), "name": name} for name in (flow_codes.BY_YOU, flow_codes.BY_CLAUDE, flow_codes.BY_TERMINAL)]
        for kind, row in flow_codes.OFFER_KINDS.items():
            op = STEPS[kind]().op if kind in STEPS else None
            items.append({"key": "offer:" + kind, "kind": kind, "phase": row.phase, "label": row.label, "op": op,
                          "from_page": flow_codes.is_sendable(kind) and op in run_request.STEP_OPERATIONS, "tell": row.tell})
        for op, operation in catalogue.CATALOGUE.items():
            area = next(name for name, table in catalogue.TABLES if table.get(op) is operation)
            items.append({"key": "op:" + op, "op": op, "area": area, "summary": " ".join(describe.summary_of(operation).split()),
                          "effects": describe.effect_words_of(operation), "data_keys": list(operation.data_keys),
                          "network": op in catalogue.NETWORK})
        items += [{"key": "unbuilt:" + key, "name": name, "status": flow_codes.NOT_BUILT, "moment": moment}
                  for key, name, moment in flow_codes.UNBUILT_STEPS]
        return cls(items)

    def of_group(self, name):
        return [one for one in self.items if one["key"].startswith(name + ":")]

    def missing(self):
        """The phases with no moment, then the moments with no phase, then the phases with no plain name (P1119), by phase."""
        phases = [one["phase"] for one in self.of_group("phase")]
        return [phase for phase in phases if phase not in MOMENTS] + [phase for phase in MOMENTS if phase not in phases] + [
            one["phase"] for one in self.of_group("phase") if not one["name"]]

    def json_text(self):
        return json.dumps({"header": HEADER, "hand_written": HAND_WRITTEN, "items": self.items}, indent=1, ensure_ascii=False) + "\n"

    def markdown(self):
        lines = ["# Design basis", "", HEADER, "", INTRO, "", "## Phases", "", "| Key | Phase | Name | Usual actor | Moment |",
                 "|---|---|---|---|---|"]
        lines += ["| `%(key)s` | %(phase)s | %(name)s | %(usual_by)s | %(moment)s |" % one for one in self.of_group("phase")]
        lines += ["", "## Statuses", "", "| Key | Word | Mark |", "|---|---|---|"]
        lines += ["| `%s` | %s | %s |" % (one["key"], one["word"] or NO_WORD, one["mark"]) for one in self.of_group("status")]
        lines += ["", "## Actors", ""] + ["- `%(key)s`: %(name)s" % one for one in self.of_group("by")]
        lines += ["", "## Offers", "", "| Key | Phase | Label | Op | From the page | Tell |", "|---|---|---|---|---|---|"]
        lines += ["| `%s` | %s | `%s` | %s | %s | %s |" % (one["key"], one["phase"], one["label"], one["op"] or NO_OP,
                                                        "yes" if one["from_page"] else "no", one["tell"] or "")
                  for one in self.of_group("offer")]
        lines += ["", "## Operations"]
        for area in dict.fromkeys(one["area"] for one in self.of_group("op")):
            lines += ["", "### %s" % area, ""]
            for one in self.of_group("op"):
                if one["area"] == area:
                    lines += ["- `%s`" % one["key"],
                              "  - Effects: %s. Data keys: %s." % (", ".join(one["effects"]) or "none, it only reads",
                                                                    ", ".join(one["data_keys"]) or "none"),
                              "  - Summary: %s" % one["summary"]]
        lines += ["", "## Unbuilt steps", "", "| Key | Name | Status | Moment |", "|---|---|---|---|"]
        lines += ["| `%(key)s` | %(name)s | %(status)s | %(moment)s |" % one for one in self.of_group("unbuilt")]
        return "\n".join(lines) + "\n"


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description="Print the design basis, or write it to %s and %s." % (MARKDOWN_PAGE, JSON_PAGE))
    parser.add_argument("--write", action="store_true", help="write %s and %s instead of printing" % (MARKDOWN_PAGE, JSON_PAGE))
    write = parser.parse_args(argv).write
    basis = DesignBasis.of()
    if write:
        (Path(root) / "docs" / "guide").mkdir(parents=True, exist_ok=True)
        (Path(root) / MARKDOWN_PAGE).write_text(basis.markdown(), encoding="utf-8")
        (Path(root) / JSON_PAGE).write_text(basis.json_text(), encoding="utf-8")
        print("wrote %s and %s" % (MARKDOWN_PAGE, JSON_PAGE))
    else:
        print(basis.markdown(), end="")


if __name__ == "__main__":
    main()
